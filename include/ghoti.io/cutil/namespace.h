/**
 * @file
 * Renames every public identifier of this library into its version namespace.
 *
 * Each line pastes the token from libver_gen.h onto the short name, so that
 * `gcu_hash64_create` becomes `ghotiio_cutil_dev_gcu_hash64_create` by the
 * time the compiler sees it.  A program keeps writing the short name; two
 * builds of this library with different BRANCH values produce disjoint symbol
 * sets and can be loaded into one process.  See CONVENTIONS.md section 4.
 *
 * This is one file rather than a block per header on purpose.  A rename must
 * be seen before the first declaration that uses the name, and with the
 * renames scattered across headers an internal header could name a type
 * before that type's rename had been read - producing two different types
 * under one spelling.  Including this file first makes that impossible.
 *
 * Add a line here whenever you add a public function, type, or variable.
 * `make check-symbols` fails the build if you forget.
 */

